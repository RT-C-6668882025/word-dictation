import assert from 'node:assert/strict';
import {executeAiCore} from '../src/aiOperations';
import {transact} from '../src/nativeAiEngine';
import {needIds,type Book} from '../src/wordbook';
import type {LearningState} from '../src/learning/operations';
let books:Book[]=['a','b'].map(id=>({id,name:id,pageSize:3,words:['x','y','z'].map(id=>({id,blocks:[{id:'text',text:id}]})),whitelist:{'0':['x','z']}}));
let learning:LearningState={profiles:[],events:[]};
const ops:any={books:()=>books,learning:()=>learning,saveLearning:(s:LearningState)=>learning=s,replaceBooks:(s:Book[])=>books=s};
const run=(n:string,a:any={})=>executeAiCore(n,a,ops);
const original=JSON.stringify(books);
run('create_algorithm',{profile:{id:'last',name:'last',version:1,algorithm:{kind:'rules',rules:{filter:{field:'order',op:'gte',value:1}}}}});
assert.equal(JSON.stringify(books),original);
assert.deepEqual(run('test_algorithm',{deckId:'a',profileId:'last'}).data.itemIds,['z']);
assert.equal(JSON.stringify(books),original);
run('set_algorithm',{deckId:'a',profileId:'last'});assert.equal(books[1].learningProfileId,undefined);
assert.deepEqual([...needIds(books[0])],['x','z']);
run('set_algorithm',{deckId:'b',profileId:'last'});
run('record_learning_event',{deckId:'a',event:{id:'e',deckId:'a',itemId:'x',type:'forgotten',at:1}});
assert.equal(learning.events.length,1);
run('reset_algorithm',{deckId:'a'});assert.equal(books[0].learningProfileId,null);assert.equal(books[1].learningProfileId,'last');
assert.throws(()=>run('create_algorithm',{profile:{id:'bad',name:'bad',version:1,algorithm:{kind:'rules',rules:{filter:{field:'oops',op:'eq',value:0}}}}}));
let state:any={books,learning,receipts:{},revision:1};const request={id:'native-create',name:'create_algorithm',arguments:{profile:{id:'native',name:'native',version:1,algorithm:{kind:'none'}}}};
const first=JSON.parse(transact(JSON.stringify(state),JSON.stringify(request)));assert.equal(first.changed,true);assert.equal(first.state.learning.profiles.length,2);
const replay=JSON.parse(transact(JSON.stringify(first.state),JSON.stringify(request)));assert.equal(replay.changed,false);assert.equal(replay.state.learning.profiles.length,2);
console.log('Learning configuration, isolation, whitelist, validation and native replay checks passed');
